// app.schema.json → one Postgres migration. Pure: same schema in, same SQL out.
// Order: tables → link and user columns → generated formulas → junctions → indexes → triggers → RLS → views → roles.
// Relies on helpers from supabase/migrations/0001_core.sql (app_can, app_role, touch_updated_at, profiles, app_roles).

import { formulaToSql, quoteIdent as q, type SqlKind } from "../formula/to-sql.ts";
import { columnOf, findField, findTable, junctionOf } from "./naming.ts";
import type { AppSchema, FieldDef, TableDef } from "./types.ts";

const lit = (v: string) => `'${v.replace(/'/g, "''")}'`;

function plainType(f: FieldDef): string | null {
  switch (f.type) {
    case "text": case "longText": case "email": case "url": case "phone": return "text";
    case "number": return "numeric";
    case "currency": return `numeric(14, ${f.precision ?? 2})`;
    case "percent": return "numeric";
    case "rating": return "smallint";
    case "checkbox": return "boolean not null default false";
    case "select": return "text";
    case "multiSelect": return "text[] not null default '{}'";
    case "date": return "date";
    case "dateTime": return "timestamptz";
    case "autoNumber": return "bigint generated by default as identity";
    case "json": return "jsonb";
    default: return null;
  }
}

function checks(t: TableDef, f: FieldDef): string[] {
  const col = q(f.key);
  const out: string[] = [];
  if (f.type === "select" && f.options?.length) {
    out.push(`alter table public.${t.key} add constraint ${t.key}_${f.key}_check check (${col} is null or ${col} in (${f.options.map((o) => lit(o.value)).join(", ")}));`);
  }
  if (f.type === "rating") out.push(`alter table public.${t.key} add constraint ${t.key}_${f.key}_check check (${col} between 1 and ${f.max ?? 5});`);
  return out;
}

function createTable(t: TableDef): string {
  const cols = [
    "id uuid primary key default gen_random_uuid()",
    "airtable_id text unique",
    "created_at timestamptz not null default now()",
    "updated_at timestamptz not null default now()",
    "created_by uuid references public.profiles(id) on delete set null",
  ];
  for (const f of t.fields) {
    const type = plainType(f);
    if (type) cols.push(`${q(f.key)} ${type}`);
  }
  return `create table public.${t.key} (\n  ${cols.join(",\n  ")}\n);\n${t.fields.flatMap((f) => checks(t, f)).join("\n")}`.trim();
}

function refColumns(t: TableDef): string[] {
  const out: string[] = [];
  for (const f of t.fields) {
    if (f.type === "link" && f.link && !f.link.multiple) {
      out.push(`alter table public.${t.key} add column ${q(`${f.key}_id`)} uuid references public.${f.link.table}(id) on delete set null;`);
      out.push(`create index on public.${t.key} (${q(`${f.key}_id`)});`);
    }
    if (f.type === "user") {
      out.push(`alter table public.${t.key} add column ${q(`${f.key}_id`)} uuid references public.profiles(id) on delete set null;`);
    }
  }
  return out;
}

function kindOf(f: FieldDef): SqlKind {
  if (["number", "currency", "percent", "rating", "autoNumber"].includes(f.type)) return "number";
  if (f.type === "checkbox") return "bool";
  if (f.type === "date" || f.type === "dateTime") return "date";
  if (["text", "longText", "email", "url", "phone", "select"].includes(f.type)) return "text";
  return "other";
}

const SQL_TYPE: Record<SqlKind, string> = { number: "numeric", text: "text", bool: "boolean", date: "date", other: "text" };

function generatedColumns(t: TableDef, notes: string[]): string[] {
  const out: string[] = [];
  const colOf = (key: string) => {
    const f = findField(t, key);
    if (!f || !plainType(f)) return undefined;
    return { column: f.key, kind: kindOf(f) };
  };
  for (const f of t.fields) {
    if (f.computed?.kind !== "formula" || f.computed.mode !== "generated") continue;
    const r = formulaToSql(f.computed.expr, colOf);
    if (r.ok) out.push(`alter table public.${t.key} add column ${q(f.key)} ${SQL_TYPE[r.kind]} generated always as (${r.sql}) stored;`);
    else notes.push(`-- ${t.key}.${f.key}: not generated (${r.reason}). Set mode "app" in app.schema.json.`);
  }
  return out;
}

function junctions(t: TableDef): string[] {
  return t.fields
    .filter((f) => f.type === "link" && f.link?.multiple)
    .map((f) => {
      const j = junctionOf(t, f);
      return [
        `create table public.${j} (`,
        `  from_id uuid not null references public.${t.key}(id) on delete cascade,`,
        `  to_id uuid not null references public.${f.link?.table}(id) on delete cascade,`,
        `  position int not null default 0,`,
        `  primary key (from_id, to_id)`,
        `);`,
        `create index on public.${j} (to_id);`,
      ].join("\n");
    });
}

function policies(table: string, accessTable: string): string {
  const read = `public.app_can(${lit(accessTable)}, 'read')`;
  const write = `public.app_can(${lit(accessTable)}, 'write')`;
  return [
    `alter table public.${table} enable row level security;`,
    `create policy ${table}_read on public.${table} for select to authenticated using (${read});`,
    `create policy ${table}_insert on public.${table} for insert to authenticated with check (${write});`,
    `create policy ${table}_update on public.${table} for update to authenticated using (${write}) with check (${write});`,
    `create policy ${table}_delete on public.${table} for delete to authenticated using (${write} and public.app_role() = 'admin');`,
  ].join("\n");
}

function lookupExpr(s: AppSchema, t: TableDef, f: FieldDef): string | null {
  if (f.computed?.kind !== "lookup") return null;
  const via = findField(t, f.computed.via);
  const target = via?.link ? findTable(s.tables, via.link.table) : undefined;
  const tf = target ? findField(target, f.computed.field) : undefined;
  const col = tf ? columnOf(tf) : null;
  if (!via?.link || !target || !col) return null;
  if (!via.link.multiple) return `(select x.${q(col)} from public.${target.key} x where x.id = t.${q(`${via.key}_id`)})`;
  return `array(select x.${q(col)} from public.${junctionOf(t, via)} j join public.${target.key} x on x.id = j.to_id where j.from_id = t.id order by j.position)`;
}

function rollupExpr(s: AppSchema, t: TableDef, f: FieldDef): string | null {
  const c = f.computed;
  if (c?.kind !== "rollup") return null;
  const src = findTable(s.tables, c.table);
  const link = src ? findField(src, c.linkField) : undefined;
  if (!src || !link?.link) return null;
  const agg = c.fn === "count" ? "count(*)" : `coalesce(${c.fn}(r.${q(c.field ?? "")}), 0)`;
  if (!link.link.multiple) return `(select ${agg} from public.${src.key} r where r.${q(`${link.key}_id`)} = t.id)`;
  return `(select ${agg} from public.${src.key} r join public.${junctionOf(src, link)} j on j.from_id = r.id where j.to_id = t.id)`;
}

function computedView(s: AppSchema, t: TableDef): string | null {
  const cols = t.fields
    .map((f) => {
      const e = f.type === "lookup" ? lookupExpr(s, t, f) : f.type === "rollup" ? rollupExpr(s, t, f) : null;
      return e ? `  ${e} as ${q(f.key)}` : null;
    })
    .filter((x): x is string => x !== null);
  if (!cols.length) return null;
  return `create or replace view public.${t.key}_computed with (security_invoker = true) as\nselect t.*,\n${cols.join(",\n")}\nfrom public.${t.key} t;`;
}

function accessList(a: "*" | string[]): string {
  return a === "*" ? "array['*']" : a.length ? `array[${a.map(lit).join(", ")}]` : "array[]::text[]";
}

function roles(s: AppSchema): string {
  const rows = s.roles.map((r) => `  (${lit(r.key)}, ${lit(r.label)}, ${accessList(r.read)}, ${accessList(r.write)})`);
  return `insert into public.app_roles (key, label, can_read, can_write) values\n${rows.join(",\n")}\non conflict (key) do update set label = excluded.label, can_read = excluded.can_read, can_write = excluded.can_write;`;
}

export function schemaToSql(s: AppSchema, header = "Generated from app.schema.json by scripts/schema-sql.ts. Do not edit; add a new migration instead."): string {
  const notes: string[] = [];
  const parts: string[] = [`-- ${header}`];
  const section = (title: string, lines: (string | null)[]) => {
    const body = lines.filter((x): x is string => Boolean(x));
    if (body.length) parts.push(`\n-- ${title}\n${body.join("\n\n")}`);
  };
  section("Tables", s.tables.map(createTable));
  section("Links to one record and people", s.tables.flatMap(refColumns));
  section("Formulas stored as generated columns", s.tables.flatMap((t) => generatedColumns(t, notes)));
  section("Links to many records (junction tables)", s.tables.flatMap(junctions));
  section("Keep updated_at current", s.tables.map((t) => `create trigger ${t.key}_touch before update on public.${t.key} for each row execute function public.touch_updated_at();`));
  section("Row level security", [
    ...s.tables.map((t) => policies(t.key, t.key)),
    ...s.tables.flatMap((t) => t.fields.filter((f) => f.type === "link" && f.link?.multiple).map((f) => policies(junctionOf(t, f), t.key))),
  ]);
  section("Lookups and rollups (views; RLS of the base table applies)", s.tables.map((t) => computedView(s, t)));
  section("Roles", [roles(s)]);
  if (notes.length) section("Notes", [notes.join("\n")]);
  return parts.join("\n") + "\n";
}
